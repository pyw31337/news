def clean_text(s):
    if not s: return ""
    s = re.sub(r"<[^>]+>", "", s)
    s = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]+)\]\]", r"\1", s)
    s = s.replace("&middot;", "·").replace("&amp;", "&").replace("&quot;", '"')
    return s.strip()


def parse_history_line(line):
    """국회 DB의 한 줄 이력 파싱"""
    line = clean_text(line)
    if not line or line.startswith("<") or line.startswith("[") or line.startswith("□") or line.startswith("■"):
        return None
    line = re.sub(r"^[▶•\-\*\s]+", "", line).strip()
    if not line: return None

    # 연도 추출 (예: "1995년", "2008.09", "1995.03~1998.02", "(2007)")
    m_yr = re.search(r"(\d{4})(?:[.\-/](\d{1,2}))?(?:\s*~\s*(\d{4})?(?:[.\-/](\d{1,2}))?)?", line)
    d = ""
    if m_yr:
        y1 = m_yr.group(1)
        m1 = m_yr.group(2)
        y2 = m_yr.group(3)
        m2 = m_yr.group(4)
        if y2:
            d = f"{y1}" + (f".{m1}" if m1 else "") + f"~{y2}" + (f".{m2}" if m2 else "")
        elif m1:
            d = f"{y1}.{m1}"
        else:
            d = f"{y1}"

    # 분류 판정
    typ = "career"
    stage = "사회 경력"

    if re.search(r"(국민학교|초등학교|중학교|고등학교|상고|공고|사범학교|전문대|대학교|대학원|학사|석사|박사|수료|졸업|중퇴|검정고시)", line) and not re.search(r"(교수|강사|총장|학장|교사|교원|연구원)", line):
        typ = "edu"
        if re.search(r"(초등|국민학교)", line):
            stage = "출생·성장"
        else:
            stage = "학업"
    elif re.search(r"(만기전역|전역|육군|해군|공군|해병|병장|중위|대위|소위|하사|부사관|군의관|법무관|의경|방위|보충역|전시근로역|면제|병역|특전사|산업기능요원)", line):
        typ = "military"
        stage = "병역"
    elif re.search(r"(대통령|국회의원|당선|의원)", line):
        typ = "election"
        stage = "정치 활동"
    elif re.search(r"(장관|차관|시장|도지사|구청장|군수|비서관|대변인|청와대|대통령실|부총리)", line):
        typ = "office"
        stage = "정치 활동"
    elif re.search(r"(당대표|원내대표|최고위원|비상대책위원|당직|대변인)", line):
        typ = "party"
        stage = "정치 활동"
    elif re.search(r"(사법시험|행정고시|입법고시|외무고시|합격)", line):
        typ = "career"
        stage = "사회 경력"

    title = re.sub(r"^\(\d{4}[^)]*\)\s*", "", line)
    title = re.sub(r"^\d{4}[^:)]*[:)]\s*", "", title).strip()

    return {
        "d": d,
        "typ": typ,
        "stage": stage,
        "title": title or line,
        "desc": "",
        "status": "fact",
        "src": "열린국회정보(국회 공개 API)"
    }


